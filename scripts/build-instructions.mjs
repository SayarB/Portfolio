// Builds agent/instructions.md from content/prompt.md and content/notes/*.md.
// Edit the content files, not the generated instructions. Runs before dev and build.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const prompt = readFileSync(join(root, "content/prompt.md"), "utf8").trim();
const notesDir = join(root, "content/notes");

const notes = readdirSync(notesDir)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => `--- NOTE: ${f.replace(/\.md$/, "")} ---\n\n${readFileSync(join(notesDir, f), "utf8").trim()}`);

if (notes.length === 0) throw new Error("No notes found in content/notes");

const out = `<!-- GENERATED by scripts/build-instructions.mjs from content/. Do not edit by hand. -->\n\n${prompt}\n\n# NOTES\n\n${notes.join("\n\n")}\n`;

mkdirSync(join(root, "agent"), { recursive: true });
writeFileSync(join(root, "agent/instructions.md"), out);
console.log(`agent/instructions.md: ${notes.length} notes, ~${Math.round(out.split(/\s+/).length)} words`);
